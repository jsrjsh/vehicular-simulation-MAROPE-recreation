"""
scripts/ns3_eval_baselines.py

Generalized ns-3/SUMO evaluation supporting all 5 methods from
CAMPAIGN_LATENCY_FIX_20260815 (ma-rope, alloffload, nooffload, ucb_bandit,
coopec_greedy), not just MA-ROPE. Goal: get real, comparable ns-3 numbers for
every method the paper's Table VI/VII/VIII report, not just one row of it.

Target comparison is CAMPAIGN_LATENCY_FIX_20260815 (the corrected Python
baseline), NOT v25 -- v25 was generated by a formula now known to be broken
(the log10 latency bug), so "matching v25" is not the right goal. "Matching
the corrected model, now under real physics" is.

Four of these five policies need NO C++ changes and NO trained network --
their actions are simple rules, computed entirely in Python:
- alloffload: always action 8 (5G-NR @ 100%)
- nooffload: always action 0 (local only)
- ucb_bandit: stateless UCB1 over 4 arms, persists across episodes (not
  reset per-episode -- a bandit's whole premise is learning from
  accumulated experience). Exact same UCB_ARMS / _ucb1_select_arm as
  run_corrected_campaign.py.
- coopec_greedy: hand-crafted rule using task_type's FIXED cpu_cycles/D_ms
  (TASK_TYPES entries are constant per type, not randomized per-instance --
  confirmed against env/config.py) -- so despite only knowing task_type
  retroactively (see is_safety_task note below), the rule reduces to a
  static lookup: safety->local, infotainment->local, compute->offload.
  Verified: l_local(safety)=50ms vs threshold 50ms (not >, so local);
  l_local(infotainment)=250ms vs threshold 250ms (not >, so local);
  l_local(compute)=1000ms vs threshold 500ms (>, so offload).
Only ma-rope needs the trained D3QN network for real inference.

Metrics NOT available from ns-3:
- Energy: out of scope everywhere, same reason as always (invalid formula).

U_PRR (2026-08-17): AG added "u_prr" to BuildExtraInfo(), mirroring u_otr's
formula exactly (same beta terms: l_ratio, e_ratio=0, delta_cbr) but with
alpha*prr_val instead of alpha*otr_val. Verified against v2x_environment.h
directly (lines ~319-341) and cross-checked prr_val's local/no-tx default
(1.0) against env/environment.py's local_reliability_mode="local_success"
default -- genuinely matches, not a new bug. Tracked below alongside u_otr.

The "is_active" 30%-of-steps filter (matching u_prr_active/u_otr_active/
fleet_otr's methodology in run_corrected_campaign.py) is replicated exactly
here via the same deterministic seeded RNG formula -- this needs nothing
from ns-3, it's a pure post-hoc Python filter keyed on (seed, episode,
episode_step, agent_id).

Usage: PYTHONPATH=. python3 scripts/ns3_eval_baselines.py \
    --policy_type alloffload --n_vehicles 8 --seed 0
(run from wherever ns3gym + the compiled ns-3 engine are reachable)
"""
import argparse
import csv
import math
import sys
import os

import numpy as np
import torch

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "_claude_workspace"))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src", "maro_pe"))

from env.ns3_sumo_env import Ns3SumoV2XEnv
from scripts.run_corrected_campaign import _build_fresh

TASK_DEADLINE_MS = {"safety": 100.0, "infotainment": 500.0, "compute": 1000.0}
TASK_CPU_CYCLES = {"safety": 1e8, "infotainment": 5e8, "compute": 2e9}
CPU_FREQ_HZ = 2e9

UCB_ARMS = [0, 6, 7, 8]  # matches run_corrected_campaign.py exactly
COOPEC_LOCAL_DEADLINE_FRACTION = 0.5

# ns3gym special-cases simSeed=0 as "randomize" (see ns3_sumo_env.py), so the
# CLI's 0-indexed --seed is offset to stay clear of that and of the old
# hardcoded simSeed=42 default, keeping every (policy, N, seed) cell backed by
# a genuinely distinct ns-3 RNG stream.
SIM_SEED_BASE = 1000

CKPT_DIR_TEMPLATE = os.path.join(
    os.path.dirname(__file__), "..", "_claude_workspace", "results",
    "CAMPAIGN_LATENCY_FIX_20260815", "raw", "n{n}"
)
ENV_MODE = "baseline_recreation"
EPISODES = 5


def load_ma_rope_coord(ckpt_path, env_mode, n_agents, seed):
    _, coord = _build_fresh(env_mode, n_agents, seed)
    payload = torch.load(ckpt_path, weights_only=False)
    assert payload["n_agents"] == n_agents
    for agent, state_dict in zip(coord.agents, payload["all_agent_online_net_state_dicts"]):
        agent.online_net.load_state_dict(state_dict)
        agent.online_net.eval()
    return coord


def _ucb1_select_arm(counts, sums, t):
    """Verbatim copy of run_corrected_campaign.py's _ucb1_select_arm."""
    for a in range(len(UCB_ARMS)):
        if counts[a] == 0:
            return a
    best_a, best_val = 0, -float("inf")
    for a in range(len(UCB_ARMS)):
        mean = sums[a] / counts[a]
        bonus = math.sqrt(2.0 * math.log(t) / counts[a])
        val = mean + bonus
        if val > best_val:
            best_val, best_a = val, a
    return best_a


def coopec_action(task_type):
    """Static lookup, verified equivalent to the real per-task computation
    -- see module docstring."""
    l_local_ms = (TASK_CPU_CYCLES[task_type] / CPU_FREQ_HZ) * 1000.0
    deadline = TASK_DEADLINE_MS[task_type]
    return 8 if l_local_ms > COOPEC_LOCAL_DEADLINE_FRACTION * deadline else 0


def run_episode(env, policy_type, n_agents, seed, ep, coord, last_task_type,
                 ucb_counts, ucb_sums, ucb_t):
    # ns3gym can only vary simSeed by restarting the ns-3 process (see
    # Ns3SumoV2XEnv._connect/reset -- fixed 2026-08-18 alongside the C++ side
    # ignoring --simSeed entirely). Without a per-episode seed here, all 5
    # episodes of a run replay the identical trajectory for any policy whose
    # actions don't depend on evolving state -- confirmed against the first
    # (broken) sweep's AllOffload/CoopEC output. Every policy gets a fresh
    # seed per episode, not just the ones that visibly flatlined, since
    # MA-ROPE/UCB's apparent episode-to-episode variation under the old code
    # was actually coming from action-dependent RNG-stream desync within a
    # single replayed trajectory, not genuine independent sampling.
    episode_seed = SIM_SEED_BASE + seed * 100 + ep
    obs = env.reset(seed=episode_seed)
    done = False
    episode_step = 0

    tx_successes, tx_on_times = [], []
    tx_attempts_active, tx_failures_active = [], []  # for conditional/fleet failure rate
    step_u_otr_active = []
    step_u_prr_active = []
    step_latency_active = []

    while not done:
        episode_step += 1
        action_dict = {}
        for i in range(n_agents):
            if policy_type == "ma-rope":
                is_safety = last_task_type.get(i, "safety") == "safety"
                action_dict[i] = coord.agents[i].select_action(
                    obs[i], is_safety_task=is_safety, evaluate=True
                )
            elif policy_type == "alloffload":
                action_dict[i] = 8
            elif policy_type == "nooffload":
                action_dict[i] = 0
            elif policy_type == "ucb_bandit":
                arm = _ucb1_select_arm(ucb_counts[i], ucb_sums[i], ucb_t[i] + 1)
                action_dict[i] = UCB_ARMS[arm]
            elif policy_type == "coopec_greedy":
                task_type = last_task_type.get(i, "safety")
                action_dict[i] = coopec_action(task_type)
            else:
                raise ValueError(f"unknown policy_type {policy_type}")

        obs, rewards, dones, infos = env.step(action_dict)
        done = dones.get("__all__", False)

        for i in range(n_agents):
            info = infos[i]
            if "task_type" not in info:
                continue
            last_task_type[i] = info["task_type"]

            rat = info.get("chosen_rat", 0)
            rho = info.get("adapted_rho", 0.0)
            attempted = rat > 0 and rho > 0.0

            if policy_type == "ucb_bandit":
                arm = UCB_ARMS.index(action_dict[i])
                ucb_t[i] += 1
                ucb_counts[i][arm] += 1
                # reward proxy for the bandit: u_otr from this step
                ucb_sums[i][arm] += float(info.get("u_otr", 0.0))

            # replicate run_corrected_campaign.py's exact active-step filter
            active_rng = np.random.RandomState(seed + ep * 1000 + episode_step * 10 + i)
            is_active = active_rng.uniform(0.0, 1.0) < 0.3

            if attempted:
                success = bool(info.get("transmission_success", False))
                lat = float(info.get("latency_ms", 0.0))
                deadline = TASK_DEADLINE_MS[info["task_type"]]
                tx_successes.append(1.0 if success else 0.0)
                tx_on_times.append(1.0 if (success and lat <= deadline) else 0.0)
                if is_active:
                    tx_attempts_active.append(1)
                    tx_failures_active.append(0 if success else 1)

            if is_active:
                step_u_otr_active.append(float(info.get("u_otr", 0.0)))
                step_u_prr_active.append(float(info.get("u_prr", 0.0)))
                if attempted:
                    step_latency_active.append(float(info.get("latency_ms", 0.0)))

    fleet_otr = float(np.mean(tx_on_times)) if tx_on_times else 1.0
    prr = float(np.mean(tx_successes)) if tx_successes else 1.0
    u_otr = float(np.mean(step_u_otr_active)) if step_u_otr_active else 0.0
    u_prr = float(np.mean(step_u_prr_active)) if step_u_prr_active else 0.0
    lat_active = float(np.mean(step_latency_active)) if step_latency_active else 0.0

    n_attempts = len(tx_attempts_active)
    n_failures = sum(tx_failures_active)
    conditional_fail_rate = (n_failures / n_attempts) if n_attempts > 0 else 0.0
    fleet_fail_rate = (n_failures / (episode_step * n_agents)) if episode_step > 0 else 0.0

    return {
        "fleet_otr": fleet_otr,
        "prr": prr,
        "u_otr_active": u_otr,
        "u_prr_active": u_prr,
        "latency_active_ms": lat_active,
        "conditional_tx_failure_rate": conditional_fail_rate,
        "fleet_tx_failure_rate": fleet_fail_rate,
    }, last_task_type


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--policy_type", required=True,
                         choices=["ma-rope", "alloffload", "nooffload", "ucb_bandit", "coopec_greedy"])
    parser.add_argument("--n_vehicles", type=int, required=True, choices=[8, 16, 32])
    parser.add_argument("--seed", type=int, required=True)
    parser.add_argument("--episodes", type=int, default=EPISODES)
    args = parser.parse_args()

    coord = None
    if args.policy_type == "ma-rope":
        ckpt_path = f"{CKPT_DIR_TEMPLATE.format(n=args.n_vehicles)}/ma-rope_seed{args.seed}.pt"
        print(f"Loading checkpoint: {ckpt_path}")
        coord = load_ma_rope_coord(ckpt_path, ENV_MODE, args.n_vehicles, args.seed)

    sim_seed = SIM_SEED_BASE + args.seed
    print(f"Connecting to ns-3 OpenGym backend (policy={args.policy_type}, n_vehicles={args.n_vehicles}, simSeed={sim_seed})...")
    env = Ns3SumoV2XEnv(n_vehicles=args.n_vehicles, max_steps=200, start_sim=True, seed=sim_seed)

    last_task_type = {}
    # UCB state persists across episodes (see module docstring)
    ucb_counts = {i: [0] * len(UCB_ARMS) for i in range(args.n_vehicles)}
    ucb_sums = {i: [0.0] * len(UCB_ARMS) for i in range(args.n_vehicles)}
    ucb_t = {i: 0 for i in range(args.n_vehicles)}

    ep_results = []
    for ep in range(args.episodes):
        result, last_task_type = run_episode(
            env, args.policy_type, args.n_vehicles, args.seed, ep, coord,
            last_task_type, ucb_counts, ucb_sums, ucb_t,
        )
        print(f"  episode {ep}: " + " ".join(f"{k}={v:.4f}" for k, v in result.items()))
        ep_results.append(result)

    env.close()

    out_dir = os.path.join(os.path.dirname(__file__), "..", "results", "ns3_eval_baselines")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, f"{args.policy_type}_n{args.n_vehicles}_seed{args.seed}.csv")
    fieldnames = ["episode"] + list(ep_results[0].keys())
    with open(out_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for ep, r in enumerate(ep_results):
            writer.writerow({"episode": ep, **r})

    means = {k: float(np.mean([r[k] for r in ep_results])) for k in ep_results[0]}
    print(f"\nMean over {args.episodes} episodes: {means}")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
