#!/bin/zsh
# Builds the paper and writes a timestamped pair into the PROJECT folder (next to figures/, references.bib):
#   MA_ROPE_TVT_v24_PureSim_<YYYYMMDD-HHMM>_LATEST.tex / .pdf
# Any earlier *_LATEST.* pair is renamed (drops "_LATEST") and moved to releases_archive/.
set -e
cd "${0:A:h}"
setopt null_glob
STAMP=$(date +%Y%m%d-%H%M)
BASE="MA_ROPE_TVT_v24_PureSim_${STAMP}_LATEST"
mkdir -p releases_archive
for f in MA_ROPE_TVT_v24_PureSim_*_LATEST.tex MA_ROPE_TVT_v24_PureSim_*_LATEST.pdf; do mv "$f" "releases_archive/${f/_LATEST/}"; done
# 1) build from sources (main.tex is the working driver, not a deliverable name)
pdflatex -interaction=nonstopmode -halt-on-error main.tex >/dev/null
bibtex main >/dev/null || true
pdflatex -interaction=nonstopmode main.tex >/dev/null
pdflatex -interaction=nonstopmode main.tex >/dev/null
# 2) flatten all \input{} into one stamped .tex that compiles from this folder
python3 - "$BASE" <<'PY'
import re,sys
def expand(t):
    return re.sub(r'\\input\{([^}]+)\}', lambda m: expand(open(m.group(1)+('' if m.group(1).endswith('.tex') else '.tex')).read()), t)
s=expand(open('main.tex').read())
open(f'{sys.argv[1]}.tex','w').write(f'% Release {sys.argv[1]} - generated by release.sh from main.tex + sections/tables/figures\n'+s)
PY
# 3) the PDF is built FROM the stamped tex, so the pair is guaranteed consistent
pdflatex -interaction=nonstopmode "$BASE.tex" >/dev/null && bibtex "$BASE" >/dev/null || true
pdflatex -interaction=nonstopmode "$BASE.tex" >/dev/null && pdflatex -interaction=nonstopmode "$BASE.tex" >/dev/null
grep -cE '^! |Overfull|undefined' "$BASE.log" | sed 's/^/log problems: /'
pdfinfo "$BASE.pdf" | grep Pages
pdftotext "$BASE.pdf" - | grep -c '\[?\]' | sed 's/^/unresolved [?]: /' || true
rm -f "$BASE".aux "$BASE".bbl "$BASE".blg "$BASE".out "$BASE".log
echo "Released: $BASE.{tex,pdf}"
